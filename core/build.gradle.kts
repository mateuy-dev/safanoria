// Embeds schema/*.json and the version into core, so the CLI checks exactly the schemas this
// repository publishes.
val generateEmbedded = tasks.register("generateEmbedded") {
    val schemaDir = rootProject.layout.projectDirectory.dir("schema")
    val ticketSchema = schemaDir.file("ticket.schema.json")
    val configSchema = schemaDir.file("safanoria.schema.json")
    val version = project.version.toString()
    val outDir = layout.buildDirectory.dir("generated/embedded")
    inputs.files(ticketSchema, configSchema)
    inputs.property("version", version)
    outputs.dir(outDir)
    doLast {
        // Multi-dollar raw strings: a single $ (as in "$schema") stays literal.
        fun raw(file: RegularFile) = "\$\$\"\"\"" + file.asFile.readText() + "\"\"\""
        val out = outDir.get().file("dev/mateuy/safanoria/core/Embedded.kt").asFile
        out.parentFile.mkdirs()
        out.writeText(
            """
            |// Generated by core/build.gradle.kts from schema/ and gradle.properties. Do not edit.
            |package dev.mateuy.safanoria.core
            |
            |public object Embedded {
            |    public const val VERSION: String = "$version"
            |    public const val TICKET_SCHEMA: String = ${raw(ticketSchema)}
            |    public const val CONFIG_SCHEMA: String = ${raw(configSchema)}
            |}
            |""".trimMargin()
        )
    }
}

// Tests read this repository's schema/examples and tickets, and optionally other local
// repositories' tickets (SAFANORIA_EXTRA_REPOS, paths separated by the OS path separator).
val testEnvironment = buildMap {
    put("SAFANORIA_REPO_ROOT", rootDir.absolutePath)
    System.getenv("SAFANORIA_EXTRA_REPOS")?.let { put("SAFANORIA_EXTRA_REPOS", it) }
}
// Environment variables aren't task inputs by default: without inputs.property, changing
// SAFANORIA_EXTRA_REPOS would reuse a cached test result.
tasks.withType<Test>().configureEach {
    testEnvironment.forEach { (k, v) -> environment(k, v) }
    inputs.property("testEnvironment", testEnvironment)
}
tasks.withType<org.jetbrains.kotlin.gradle.targets.native.tasks.KotlinNativeTest>().configureEach {
    testEnvironment.forEach { (k, v) -> environment(k, v) }
    inputs.property("testEnvironment", testEnvironment)
}

